"""Owned deterministic multi-domain research data; deliberately not a benchmark.

The frozen 135M/360M discovery data already had its hidden prompts consumed, so it cannot be
reused as fresh held-out evidence. This module generates a NEW dataset from code:

* five exact-answer domains with fixed templates and index-derived operands,
* eight disjoint roles sized for a bounded CPU run,
* no downloads, no third-party questions, no pretrained-corpus text,
* a manifest of per-file and per-prompt hashes plus explicit non-claims.

It is owned fixture-quality data. Baseline accuracy is a format/arithmetic diagnostic, not a
generalization or reasoning benchmark, and nothing here is decontaminated against any model's
pretraining corpus.
"""

import hashlib
import json
from dataclasses import asdict
from pathlib import Path

from ..data import Sample, prompt_key
from .contracts import ROLES, Budget, Recipe
from .provenance import regular, write_once

GENERATOR = "ouroboros-owned-template-v1"
LICENSE = "MIT (this repository); generated by code, no third-party question text"
DOMAINS = ("arithmetic", "comparison", "conversion", "sequence", "divisibility")

# Balanced, deliberately small: a CPU run must finish inside the wall budget.
ROLE_SIZES = {
    "train": 150,
    "practice": 30,
    "validation": 30,
    "reserved": 40,
    "final": 40,
    "robustness": 30,
    "retention": 30,
    "followup": 30,
}

ROLE_ORDER = tuple(ROLE_SIZES)

ROLE_SALT = {
    "train": 11,
    "practice": 23,
    "validation": 37,
    "reserved": 53,
    "final": 71,
    "robustness": 89,
    "retention": 101,
    "followup": 113,
}


def _mix(*values):
    digest = hashlib.sha256(":".join(str(v) for v in values).encode()).digest()
    return int.from_bytes(digest[:8], "big")


def arithmetic(n):
    left, right = 10 + n % 89, 10 + (n // 89) % 89
    operator = ("+", "-", "*")[(n // 7921) % 3]
    if operator == "-":
        left, right = max(left, right), min(left, right)
        value = left - right
    elif operator == "*":
        left, right = n % 13 + 2, (n // 13) % 12 + 2
        value = left * right
    else:
        value = left + right
    forms = ("What is {l} {o} {r}?", "Compute {l} {o} {r}.", "{l} {o} {r} equals what?")
    return forms[(n // 3) % 3].format(l=left, o=operator, r=right), str(value)


def comparison(n):
    left, right = 100 + n % 900, 100 + (n // 900) % 900
    if left == right:
        right = 100 + (right - 99) % 900
    larger = max(left, right)
    forms = (
        "Which is larger, {l} or {r}?",
        "Between {l} and {r}, which number is greater?",
        "Of {l} and {r}, state the bigger number.",
    )
    return forms[(n // 3) % 3].format(l=left, r=right), str(larger)


def conversion(n):
    units = (
        ("hours", "minutes", 60),
        ("minutes", "seconds", 60),
        ("days", "hours", 24),
        ("metres", "centimetres", 100),
        ("kilograms", "grams", 1000),
    )
    source, target, factor = units[n % len(units)]
    amount = 2 + (n // len(units)) % 8
    forms = (
        "Convert {a} {s} to {t}.",
        "How many {t} are in {a} {s}?",
        "{a} {s} equals how many {t}?",
    )
    return forms[(n // 3) % 3].format(a=amount, s=source, t=target), str(amount * factor)


def sequence(n):
    digits = [1 + (n // (3**i)) % 9 for i in range(3)]
    if (n // 7) % 2:
        return "Reverse the digits of {v}.".format(v="".join(map(str, digits))), "".join(
            map(str, reversed(digits))
        )
    return (
        "Sort {v} in ascending order.".format(v=", ".join(map(str, digits))),
        " ".join(map(str, sorted(digits))),
    )


def divisibility(n):
    divisor = 2 + (n // 89) % 9
    if (n // 801) % 2:
        value = divisor * (2 + (n // 7209) % 7)
    else:
        value = divisor * (2 + (n // 7209) % 7) + 1
    forms = (
        "Is {v} divisible by {d}? Answer yes or no.",
        "Is {v} a multiple of {d}? Answer yes or no.",
        "Does {d} divide {v}? Answer yes or no.",
    )
    answer = "yes" if value % divisor == 0 else "no"
    return forms[(n // 3) % 3].format(v=value, d=divisor), answer


GENERATORS = {
    "arithmetic": arithmetic,
    "comparison": comparison,
    "conversion": conversion,
    "sequence": sequence,
    "divisibility": divisibility,
}


def build(seed=17):
    """Return {role: [Sample, ...]} with balanced domains and globally unique prompts."""
    roles, seen = {}, {}
    for role in ROLES:
        domain_order = [DOMAINS[(i + ROLE_SALT[role]) % len(DOMAINS)] for i in range(len(DOMAINS))]
        rows = []
        for index in range(ROLE_SIZES[role]):
            domain = domain_order[index % len(DOMAINS)]
            # A globally unique fixture ordinal keeps prompts disjoint across roles without
            # revealing the answer; the domain content is still driven by the same ordinal.
            # 211 > the largest role (150) so role blocks never overlap, and 211 is coprime
            # with the generator periods (8, 5, 3), so no two roles can emit the same body.
            ordinal = seed * 100000 + ROLE_ORDER.index(role) * 211 + index
            body, target = GENERATORS[domain](ordinal)
            instruction = f"Item {ordinal}. {body}"
            key = prompt_key(instruction)
            if key in seen:
                raise ValueError(f"Generator produced a duplicate prompt in {role}")
            seen[key] = role
            rows.append(
                Sample(
                    instruction,
                    target,
                    domain,
                    f"{GENERATOR}:{seed}",
                    role in ("train", "followup"),
                )
            )
        roles[role] = rows
    return roles


def fingerprint(roles):
    return hashlib.sha256(
        json.dumps(
            {role: [s.as_dict() for s in rows] for role, rows in roles.items()},
            sort_keys=True,
        ).encode()
    ).hexdigest()


def write_dataset(directory, *, seed=17, model_path, budget=None, researcher=None):
    """Create a new dataset + foundation config; never overwrite an existing directory."""
    root = Path(directory).absolute()
    if root.exists() or root.is_symlink():
        raise FileExistsError("Research dataset requires a new directory; no overwrite")
    if any(p.is_symlink() for p in root.parents):
        raise ValueError("Dataset parent must not be symlinked")
    roles = build(seed)
    budget = budget or Budget(
        max_steps=60,
        max_seconds=3600,
        max_rss_bytes=1600 * 1024**2,
        max_seq_length=192,
        max_new_tokens=12,
        max_train_examples=256,
        max_total_steps=900,
        max_candidates=2,
        repeats=2,
        checkpoint_every=30,
        cpu_threads=2,
    )
    from .contracts import ResearchData

    admitted = ResearchData(roles)  # same admission screen the controller applies
    files = {}
    for role, rows in roles.items():
        binding = write_once(root / "data" / f"{role}.json", [sample.as_dict() for sample in rows])
        files[role] = {
            "path": f"data/{role}.json",
            "sha256": binding["sha256"],
            "count": len(rows),
        }
    manifest = {
        "schema_version": 1,
        "kind": "ouroboros-owned-research-dataset",
        "generator": GENERATOR,
        "seed": seed,
        "license": LICENSE,
        "provenance": "generated by ouroboros.research.dataset; no third-party text",
        "domains": list(DOMAINS),
        "role_sizes": ROLE_SIZES,
        "files": files,
        "dataset_sha256": admitted.fingerprint(),
        "question_overlap_screen": admitted.quality,
        "redistribution": "safe to redistribute: generated from code in this repository",
        "non_claims": [
            "not a benchmark and not comparable to GSM8K/MATH/IFEval results",
            "not decontaminated against any model's pretraining corpus",
            "format and arithmetic diagnostics only; no reasoning or generalization claim",
            "answers are exact-match strings; graders are not learned",
        ],
    }
    write_once(root / "manifest.json", manifest)
    config = {
        "schema_version": 1,
        "model": {
            "model_name_or_path": str(Path(model_path).absolute()),
            "device": "cpu",
            "torch_dtype": "float32",
            "max_new_tokens": budget.max_new_tokens,
        },
        "data": {role: f"data/{role}.json" for role in ROLES},
        "budget": asdict(budget),
        "researcher": researcher or {"kind": "host_reference"},
        "output_dir": "runs",
        "database": "experiments.sqlite3",
        "seed": 17,
        "followup_recipe": asdict(Recipe(steps=4, learning_rate=0.0001)),
    }
    write_once(root / "foundation.json", config)
    (root / "README.md").write_text(
        "# Owned research dataset\n\n"
        "Generated by `ouroboros.research.dataset` (see `manifest.json` for hashes and\n"
        "non-claims). Five exact-answer template domains, eight roles, no third-party\n"
        "question text. This is a diagnostic fixture: it is **not** a benchmark, it is not\n"
        "decontaminated against any pretraining corpus, and a gain here is not a reasoning\n"
        "or generalization result.\n",
        encoding="utf-8",
    )
    return {
        "directory": str(root),
        "config": str(root / "foundation.json"),
        "dataset_sha256": manifest["dataset_sha256"],
        "counts": {role: len(rows) for role, rows in roles.items()},
        "domains": list(DOMAINS),
        "model_downloaded": False,
        "redistributable": True,
    }


def verify_dataset(directory):
    """Re-hash every role file and confirm the manifest still describes the data on disk."""
    from ..core.checkpoints import file_sha256

    root = Path(directory).absolute()
    manifest = json.loads(regular(root / "manifest.json").read_text())
    if manifest.get("kind") != "ouroboros-owned-research-dataset":
        raise ValueError("Expected an owned research dataset manifest")
    if manifest.get("generator") != GENERATOR:
        raise ValueError("Unexpected dataset generator")
    roles = {}
    for role, entry in manifest["files"].items():
        path = regular(root / entry["path"])
        if file_sha256(path) != entry["sha256"]:
            raise ValueError(f"Dataset role file changed: {role}")
        rows = [Sample.from_dict(row) for row in json.loads(path.read_text())]
        if len(rows) != entry["count"]:
            raise ValueError(f"Dataset role count changed: {role}")
        roles[role] = rows
    from .contracts import ResearchData

    admitted = ResearchData(roles)
    if admitted.fingerprint() != manifest["dataset_sha256"]:
        raise ValueError("Dataset fingerprint changed")
    return {
        "status": "verified",
        "dataset_sha256": manifest["dataset_sha256"],
        "counts": {role: len(rows) for role, rows in roles.items()},
        "license": manifest["license"],
        "generator": GENERATOR,
        "redistributable": True,
    }


def answer_shape_check(roles):
    """Cheap sanity check that answers are short exact-match strings, not prose."""
    for role, rows in roles.items():
        for sample in rows:
            if len(sample.target) > 12 or sample.target != sample.target.strip():
                raise ValueError(f"Unexpected answer shape in {role}: {sample.target!r}")
    return True
